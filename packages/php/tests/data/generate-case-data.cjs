#!/usr/bin/env node
/*
 * Regenerates src/CaseData.php from the running Node's Unicode tables (Node 24: Unicode 17),
 * so Str::lower() matches JavaScript's String.prototype.toLowerCase() on every PHP version:
 *
 *  - LOWER: JS lowercase of the uppercase letters added after Unicode 13. Older PHP builds
 *    (8.1: Unicode 14, 8.4: Unicode 16) leave them unchanged; the ranges below are every code
 *    point whose lowercase mapping changed between Unicode 13 and 17.
 *  - CASED / CASE_IGNORABLE: the Unicode Cased and Case_Ignorable properties (PCRE class bodies),
 *    needed for the Final_Sigma rule, which mb_strtolower() only implements from PHP 8.3.
 *
 *   node tests/data/generate-case-data.cjs > src/CaseData.php
 */
const changed = [[0x1c89, 0x1c89], [0x2c2f, 0x2c2f], [0xa7c0, 0xa7dc], [0x10570, 0x10595], [0x10d50, 0x10d65], [0x16ea0, 0x16eb8]];

const hex = (c) => c.toString(16).toUpperCase().padStart(4, '0');
const lower = [];
for (const [s, e] of changed) {
  for (let c = s; c <= e; c++) {
    const ch = String.fromCodePoint(c);
    const l = ch.toLowerCase();
    if (l !== ch) lower.push(`        "\\u{${hex(c)}}" => "${[...l].map((x) => `\\u{${hex(x.codePointAt(0))}}`).join('')}",`);
  }
}

function ranges(re) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c < 0x110000 && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c;
    if (!ok && start >= 0) {
      out.push(start === c - 1 ? `\\x{${hex(start)}}` : `\\x{${hex(start)}}-\\x{${hex(c - 1)}}`);
      start = -1;
    }
  }
  // 16 ranges per line keeps the file readable.
  const lines = [];
  for (let i = 0; i < out.length; i += 16) lines.push(`        . '${out.slice(i, i + 16).join('')}'`);
  return lines.join('\n').replace(/^ {8}\. /, '        ');
}

process.stdout.write(`<?php

declare(strict_types=1);

namespace PhpDiffText;

/**
 * Unicode data for Str::lower(). Generated by tests/data/generate-case-data.cjs from
 * Node ${process.versions.node} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit by hand.
 *
 * @internal
 */
final class CaseData
{
    /** JS lowercase of the letters whose mapping is newer than Unicode 13 (for strtr). */
    public const LOWER = [
${lower.join('\n')}
    ];

    /** Unicode Cased property, as a PCRE character-class body (use with /u). */
    public const CASED =
${ranges(/^\p{Cased}$/u)};

    /** Unicode Case_Ignorable property, as a PCRE character-class body (use with /u). */
    public const CASE_IGNORABLE =
${ranges(/^\p{Case_Ignorable}$/u)};
}
`);
